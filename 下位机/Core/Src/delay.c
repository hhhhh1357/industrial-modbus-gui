//延时nus
//nus:要延时的us数.	
//nus:0~190887435(最大值即2^32/fac_us@fac_us=22.5)	    								   
void delay_us(uint32_t nus)
{		
	//nus=nus/8;
	for(uint32_t i=0;i<(nus*9);i++)
	{
		__NOP();//1000/72 ns=13.888888ns
	}								    
}  
	
	 



































